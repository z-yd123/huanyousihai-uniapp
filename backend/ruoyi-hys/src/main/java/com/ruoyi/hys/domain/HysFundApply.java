package com.ruoyi.hys.domain;

import java.time.LocalDateTime;
import com.ruoyi.common.core.domain.BaseEntity;

/**
 * 充值 / 提现申请。提现手续费 {@code fee} 按 6% 分向下取整，{@code actualAmount} 为实际到账。
 */
public class HysFundApply extends BaseEntity {

    private static final long serialVersionUID = 1L;

    private Long applyId;
    private String applyNo;
    private Long memberId;
    /** RECHARGE / WITHDRAW */
    private String applyType;
    private Long amount;
    private Long fee;
    private Long actualAmount;
    private Integer status;
    private String accountName;
    private String accountNo;
    private String bankName;
    private String auditBy;
    private LocalDateTime auditTime;
    private String auditRemark;

    private String memberName;
    private String memberPhone;
    private Long memberBalance;

    public Long getApplyId() {
        return applyId;
    }

    public void setApplyId(Long applyId) {
        this.applyId = applyId;
    }

    public String getApplyNo() {
        return applyNo;
    }

    public void setApplyNo(String applyNo) {
        this.applyNo = applyNo;
    }

    public Long getMemberId() {
        return memberId;
    }

    public void setMemberId(Long memberId) {
        this.memberId = memberId;
    }

    public String getApplyType() {
        return applyType;
    }

    public void setApplyType(String applyType) {
        this.applyType = applyType;
    }

    public Long getAmount() {
        return amount;
    }

    public void setAmount(Long amount) {
        this.amount = amount;
    }

    public Long getFee() {
        return fee;
    }

    public void setFee(Long fee) {
        this.fee = fee;
    }

    public Long getActualAmount() {
        return actualAmount;
    }

    public void setActualAmount(Long actualAmount) {
        this.actualAmount = actualAmount;
    }

    public Integer getStatus() {
        return status;
    }

    public void setStatus(Integer status) {
        this.status = status;
    }

    public String getAccountName() {
        return accountName;
    }

    public void setAccountName(String accountName) {
        this.accountName = accountName;
    }

    public String getAccountNo() {
        return accountNo;
    }

    public void setAccountNo(String accountNo) {
        this.accountNo = accountNo;
    }

    public String getBankName() {
        return bankName;
    }

    public void setBankName(String bankName) {
        this.bankName = bankName;
    }

    public String getAuditBy() {
        return auditBy;
    }

    public void setAuditBy(String auditBy) {
        this.auditBy = auditBy;
    }

    public LocalDateTime getAuditTime() {
        return auditTime;
    }

    public void setAuditTime(LocalDateTime auditTime) {
        this.auditTime = auditTime;
    }

    public String getAuditRemark() {
        return auditRemark;
    }

    public void setAuditRemark(String auditRemark) {
        this.auditRemark = auditRemark;
    }

    public String getMemberName() {
        return memberName;
    }

    public void setMemberName(String memberName) {
        this.memberName = memberName;
    }

    public String getMemberPhone() {
        return memberPhone;
    }

    public void setMemberPhone(String memberPhone) {
        this.memberPhone = memberPhone;
    }

    public Long getMemberBalance() {
        return memberBalance;
    }

    public void setMemberBalance(Long memberBalance) {
        this.memberBalance = memberBalance;
    }
}
