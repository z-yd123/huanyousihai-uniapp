/* 轻量 base64（仅 ASCII，够用） */
function b64(str) {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
  let out = ''
  for (let i = 0; i < str.length; i += 3) {
    const c1 = str.charCodeAt(i)
    const c2 = str.charCodeAt(i + 1)
    const c3 = str.charCodeAt(i + 2)
    const e1 = c1 >> 2
    const e2 = ((c1 & 3) << 4) | (isNaN(c2) ? 0 : c2 >> 4)
    const e3 = isNaN(c2) ? 64 : ((c2 & 15) << 2) | (isNaN(c3) ? 0 : c3 >> 6)
    const e4 = isNaN(c3) ? 64 : c3 & 63
    out += chars[e1] + chars[e2] + (e3 === 64 ? '=' : chars[e3]) + (e4 === 64 ? '=' : chars[e4])
  }
  return out
}

const cache = {}

export function iconDataUri(name, color = '#1C2B26', weight = 1.5) {
  const key = name + '|' + color + '|' + weight
  if (cache[key]) return cache[key]
  const body = PATHS[name] || PATHS.dot
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="${color}" ` +
    `stroke-width="${weight}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`
  const uri = 'data:image/svg+xml;base64,' + b64(svg)
  cache[key] = uri
  return uri
}

